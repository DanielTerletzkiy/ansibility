package de.terletzkiy.ansibility.runtime

import com.intellij.DynamicBundle
import org.jetbrains.annotations.Nls
import org.jetbrains.annotations.PropertyKey

private const val BUNDLE = "messages.AnsibilityRuntimeBundle"

/** Messages of the runtime area (documentation sources, local Ansible install). */
object AnsibilityRuntimeBundle : DynamicBundle(BUNDLE) {
    @Nls
    fun message(@PropertyKey(resourceBundle = BUNDLE) key: String, vararg params: Any): String =
        getMessage(key, *params)
}
